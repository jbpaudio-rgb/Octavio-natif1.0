"""tables and constants of the voices / Minimoog / Prophet / drum engines -> src/c_tables_gen.h (run by hand, output committed)"""
import math, os
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
FS = 44100.0
q = lambda x: int(round(x * 65536))
o = ['/* generated by tools/gen_c_tables.py */', '#pragma once', '#include <stdint.h>']
def d(n, v): o.append('#define %s (%d)' % (n, v))
d('C_L2_MINC', q(math.log2(261.63 / FS * 2**32)))          # phase increment of C4, log2
d('C_L2_FC0', q(math.log2(30 * math.pi / FS)))              # moog cutoff: x = pi fc / FS
d('C_L2_AI0', q(30 - math.log2(.001 * FS)))                 # attack step Q30 per sample for t = 1 ms
d('C_L2_ATK', q(math.log2(2000)))                           # attack range 1 ms .. 2 s
d('C_L2_DC0', q(34 - math.log2(.005 * FS)))                 # 4/(t FS) in Q32 for t = 5 ms
d('C_L2_DCR', q(math.log2(600)))                            # decay range 5 ms .. 3 s
d('C_L2_DC8', q(34 - math.log2(.008 * FS)))                 # the fixed 8 ms release
d('C_L2_NZ0', q(math.log2(2 * math.pi * 200 / FS)))
d('C_L2_NZR', q(math.log2(100)))
d('C_L2_NZ1', q(math.log2(2 * math.pi * 20 / FS)))
d('C_L2_NZS', q(math.log2(250)))
o.append('static const int16_t TANH_TAB[257] = {' + ','.join(str(int(round(math.tanh(-4 + i / 32) * 32767))) for i in range(257)) + '};')
o.append('static const uint16_t EXPM_TAB[257] = {' + ','.join(str(min(65535, int(round((1 - math.exp(-i / 64)) * 65536)))) for i in range(257)) + '};')
open(os.path.join(root, 'src/c_tables_gen.h'), 'w').write('\n'.join(o) + '\n')

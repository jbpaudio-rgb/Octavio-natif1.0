"""Static chrome of the prototype's screen (fixed text, boxes) as alpha masks cut from its captures (tools/ref_all.js) -> src/masks_gen.h
usage: make_masks.py REFDIR     (REFDIR holds lfo0.png ...)"""
import sys
from PIL import Image
import numpy as np
ref = sys.argv[1]
out = ['/* generated by tools/make_masks.py from captures of the prototype */']
def mask(name, png, x0, y0, w, h, fg, bg=4):
    a = np.array(Image.open(f'{ref}/{png}.png').convert('RGB')).astype(float)[y0:y0 + h, x0:x0 + w, 1]
    al = np.clip(np.round((a - bg) / (fg - bg) * 255), 0, 255).astype(int)
    out.append(f'static const uint8_t {name}[{w * h}] = {{' + ','.join(map(str, al.flatten())) + '};')
mask('MK_SYNC', 'lfo0', 212, 10, 18, 6, 141)          # the "sync" word (#8d8a83); its box is drawn with rects
open(sys.argv[2] if len(sys.argv) > 2 else 'src/masks_gen.h', 'w').write('\n'.join(out) + '\n')

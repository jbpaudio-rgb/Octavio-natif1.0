#!/usr/bin/env python3
"""tables for the engine: sine, 2^x, one-pole g(c) of the Vactrol engine -> src/tables_gen.c"""
import math, os
root=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
o=['/* generated by tools/gen_tables.py */','#include "octavio.h"',
   'const int16_t SIN_TAB[1025] = {']
v=[int(round(math.sin(2*math.pi*i/1024)*32767)) for i in range(1025)]
for i in range(0,1025,16):o.append(','.join(map(str,v[i:i+16]))+',')
o.append('};')
o.append('const uint32_t EXP2_TAB[257] = {')   # 2^(i/256) in Q30 (1.0 .. 2.0)
e=[int(round(2**(i/256)*2**30)) for i in range(257)]
for i in range(0,257,8):o.append(','.join(map(str,e[i:i+8]))+',')
o.append('};')
# Vactrol low-pass: w = 2*pi*50*2^(9c)/FS, g = w/(1+w), c = 0..1 in 1/256 steps, Q16
o.append('const uint16_t LPG_TAB[257] = {')
g=[]
for i in range(257):
    w=2*math.pi*50*2**(9*i/256)/44100;g.append(int(round(w/(1+w)*65536)))
for i in range(0,257,16):o.append(','.join(map(str,g[i:i+16]))+',')
o.append('};')
open(f'{root}/src/tables_gen.c','w').write('\n'.join(o)+'\n')

# constants for the Vactrol engine's parameter maps (all log2 in Q16)
L=lambda x:int(round(math.log2(x)*65536))
c=['/* generated by tools/gen_tables.py */','#pragma once']
def d(n,v):c.append(f'#define {n} ({v})')
d('K_INC0',int(round((math.log2(20)+32-math.log2(44100))*65536)))   # inc32 = 2^(K_INC0 + s*K_L200 + (note-60)/12)
d('K_L200',L(200))
d('K_LOG2FS',L(44100))
d('K_DEC0',L(0.002))          # decay d = .002 * 1000^s seconds
d('K_L1000',L(1000))
d('K_ATK0',L(44.1))           # attack samples = 44.1 * 2000^s
d('K_L2000',L(2000))
d('K_EDEC0',int(round(math.log2(5/(0.005*44100))*65536)))   # 5/(edec*FS), edec=.005*600^s
d('K_L600',L(600))
d('K_LOG2_20',L(20))
open(f'{root}/src/consts_gen.h','w').write('\n'.join(c)+'\n')

#!/usr/bin/env python3
"""assets/octavio_logo.png -> src/logo_gen.h: the start-up screen's logo as an 8-bit alpha mask (gfx_mask), scaled to LOGO_W px wide."""
import os, sys
from PIL import Image
here = os.path.dirname(os.path.abspath(__file__))
LOGO_W = 208
im = Image.open(os.path.join(here, '..', 'assets', 'octavio_logo.png')).convert('RGBA')
a = im.split()[3]
h = max(1, round(a.height * LOGO_W / a.width))
a = a.resize((LOGO_W, h), Image.LANCZOS)
px = list(a.tobytes())
with open(os.path.join(here, '..', 'src', 'logo_gen.h'), 'w') as f:
    f.write('/* generated by tools/gen_logo.py from assets/octavio_logo.png: do not edit */\n')
    f.write('#define LOGO_W %d\n#define LOGO_H %d\n' % (LOGO_W, h))
    f.write('static const uint8_t LOGO_MASK[LOGO_W * LOGO_H] = {\n')
    for i in range(0, len(px), 24):
        f.write(' ' + ','.join(str(v) for v in px[i:i+24]) + ',\n')
    f.write('};\n')
print('logo %dx%d' % (LOGO_W, h))

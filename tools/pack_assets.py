#!/usr/bin/env python3
"""assets/fonts.json + assets/knob.json -> src/assets_gen.c (fonts, knob sprites)"""
import json, os
root=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
fonts=json.load(open(f'{root}/assets/fonts.json'))
knob=json.load(open(f'{root}/assets/knob.json'))
o=['/* generated by tools/pack_assets.py from Chrome renders of the prototype - do not edit */',
   '#include "octavio.h"']
names=[]
for fn,F in fonts.items():
    CH=F['chars']
    data=[];gl=[[] for _ in range(4)]
    for ph in range(4):
        for ch in CH:
            g=F['phases'][ph][ch]
            gl[ph].append((len(data),g['w'],g['h'],g['dx'],g['dy']))
            data+=g['a']
    # code -> glyph index: 32..126 as present, specials 1..6
    mp=[255]*128
    for i,ch in enumerate(CH):
        c=ord(ch)
        if c<127: mp[c]=i
    for j,ch in enumerate(['\u25CF','\u00B7','\u2014','\u2026','\u25B6','\u25A0']): mp[1+j]=CH.index(ch)
    o.append(f'static const uint8_t fd_{fn}[{len(data)}] = {{')
    for i in range(0,len(data),32):o.append(','.join(map(str,data[i:i+32]))+',')
    o.append('};')
    o.append(f'static const uint8_t fm_{fn}[128] = {{'+','.join(map(str,mp))+'};')
    o.append(f'static const glyph_t fg_{fn}[{4*len(CH)}] = {{')
    for ph in range(4):o.append(','.join('{%d,%d,%d,%d,%d}'%g for g in gl[ph])+',')
    o.append('};')
    names.append((fn,int(round(F['adv']*64)),F['size'],len(CH)))
o.append('const font_t FONTS[%d] = {'%len(names))
for fn,adv,size,n in names:
    o.append('  {fg_%s, fd_%s, fm_%s, %d, %d, %d},'%(fn,fn,fn,n,adv,int(round(size*64))))
o.append('};')
# knob sprites: premultiplied RGB + alpha, packed as 4 bytes
for i,s in enumerate(knob):
    flat=[v for p in s['px'] for v in p]
    o.append(f'const uint8_t KNOB_SPR{i}[{len(flat)}] = {{')
    for j in range(0,len(flat),32):o.append(','.join(map(str,flat[j:j+32]))+',')
    o.append('};')
open(f'{root}/src/assets_gen.c','w').write('\n'.join(o)+'\n')
print('assets_gen.c',sum(len(l) for l in o)//1024,'KB text')
